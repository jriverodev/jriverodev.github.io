// Captura de elementos de la interfaz (DOM)
const txtData = document.getElementById('txtData');
const txtPrefix = document.getElementById('txtPrefix');
const lblPreviewNomenclatura = document.getElementById('lblPreviewNomenclatura');
const compressedInput = document.getElementById('compressedInput');
const processBtn = document.getElementById('processBtn');
const logOutput = document.getElementById('logOutput');
const warningTxt = document.getElementById('warningTxt');

let empleadosMap = new Map();

// Cargar prefijo guardado en localStorage
if (txtPrefix) {
    const savedPrefix = localStorage.getItem('renombrapdf_prefix');
    if (savedPrefix !== null) {
        txtPrefix.value = savedPrefix;
    }
}

// Función para sanitizar nombres de archivos (eliminar caracteres no permitidos por SO)
function sanitizeFileName(str) {
    return str.replace(/[/\\?%*:|"<>]/g, '').trim();
}

// Actualizar vista previa de la nomenclatura
function updateNomenclaturaPreview() {
    if (!lblPreviewNomenclatura) return;
    const rawPrefix = txtPrefix ? txtPrefix.value.trim() : '';
    const cleanPrefix = sanitizeFileName(rawPrefix);
    if (cleanPrefix) {
        lblPreviewNomenclatura.textContent = `${cleanPrefix} 12345678 NOMBRE APELLIDO.pdf`;
    } else {
        lblPreviewNomenclatura.textContent = `12345678 NOMBRE APELLIDO.pdf`;
    }
}

if (txtPrefix) {
    txtPrefix.addEventListener('input', () => {
        const rawPrefix = txtPrefix.value;
        localStorage.setItem('renombrapdf_prefix', rawPrefix);
        updateNomenclaturaPreview();
    });
    updateNomenclaturaPreview();
}

// Consola visual en pantalla
function log(message) {
    logOutput.textContent += message + "\n";
    logOutput.scrollTop = logOutput.scrollHeight;
}

// Convertir base de datos de texto a mapa estructurado en memoria
function parseEmpleados() {
    empleadosMap.clear();
    const lines = txtData.value.split('\n');
    let count = 0;

    lines.forEach(line => {
        if (!line.trim() || line.startsWith('cedula')) return;
        const partes = line.split(',');
        if (partes.length >= 3) {
            const cedula = partes[0].trim();
            const nombre = partes[1].trim();
            const proceso = partes[2].trim();
            empleadosMap.set(cedula, { nombre, proceso });
            count++;
        }
    });

    if (count > 0) {
        log(`✔️ Base de datos sincronizada: ${count} empleados cargados.`);
        compressedInput.disabled = false;
        processBtn.disabled = false;
        warningTxt.classList.add('hidden');
    } else {
        log(`❌ Error: Verifica el formato del cuadro de texto.`);
        compressedInput.disabled = true;
        processBtn.disabled = true;
        warningTxt.classList.remove('hidden');
    }
}

// Inicializar base de datos al arrancar
txtData.value = defaultDatabase;
txtData.addEventListener('input', parseEmpleados);
parseEmpleados();

// Evento disparador para procesar y ordenar los documentos
processBtn.addEventListener('click', async () => {
    const file = compressedInput.files[0];
    if (!file) {
        log("❌ Por favor, selecciona un archivo .zip o .rar primero.");
        return;
    }

    log(`🚀 Analizando archivo comprimido: ${file.name}`);
    processBtn.disabled = true;

    try {
        const nuevoZip = new JSZip(); // El contenedor final descargado siempre será un .zip ordenado
        const extension = file.name.split('.').pop().toLowerCase();
        let listaArchivos = []; 

        if (extension === 'zip') {
            log("📂 Formato ZIP detectado. Abriendo contenedor...");
            const zip = new JSZip();
            const loadedZip = await zip.loadAsync(file);
            
            const promesas = [];
            loadedZip.forEach((relativeArrPath, zipEntry) => {
                if (zipEntry.dir) return; // Omitir directorios puros

                // Aislar el nombre base del PDF (omitiendo directorios internos antiguos)
                const fullFileName = zipEntry.name.split('/').pop();
                if (!fullFileName.toLowerCase().endsWith('.pdf')) return;

                const promesa = zipEntry.async("blob").then(content => {
                    listaArchivos.push({ nombre: fullFileName, blob: content });
                });
                promesas.push(promesa);
            });
            await Promise.all(promesas);

        } else if (extension === 'rar') {
            log("📂 Formato RAR detectado. Verificando motor de descompresión...");
            
            // Esta librería específica (wcchoi) expone el constructor 'unrar' o 'Module.unrar' en window
            const unrarConstructor = window.unrar || (window.Module && window.Module.unrar);
            
            if (!unrarConstructor) {
                throw new Error("Fallo crítico: El motor unrar no se encuentra activo en el entorno global de la ventana.");
            }

            log("✔️ Motor RAR (libunrar-js) detectado con éxito.");
            const arrayBuffer = await file.arrayBuffer();
            log("📦 Extrayendo paquetes internos del archivo RAR...");
            
            // Instanciar la clase pasándole el ArrayBuffer binario crudo del fichero
            const extractor = new unrarConstructor(arrayBuffer);
            
            // El método de wcchoi para obtener los nombres completos de archivos internos es .list()
            const filesList = extractor.list(); 

            filesList.forEach(fileName => {
                // Si termina en barra, representa una carpeta interna; la omitimos
                if (fileName.endsWith('/') || fileName.endsWith('\\')) return;

                // Extraer únicamente el nombre final del PDF, removiendo rutas relativas
                const fullFileName = fileName.split('\\').pop().split('/').pop();
                if (!fullFileName.toLowerCase().endsWith('.pdf')) return;

                // El método .extract(nombre) extrae los datos puros y devuelve un Uint8Array
                const fileData = extractor.extract(fileName);
                if (!fileData) return;

                const blob = new Blob([fileData], { type: "application/pdf" });
                listaArchivos.push({ nombre: fullFileName, blob: blob });
            });
        } else {
            throw new Error("Formato inválido. Sube únicamente archivos de tipo .zip o .rar");
        }

        log(`🔍 Analizando ${listaArchivos.length} PDFs extraídos...`);
        let procesadosOk = 0;

        // Bucle de clasificación y renombrado por expresiones regulares
        listaArchivos.forEach(archivo => {
            // Captura la secuencia de números ubicada exactamente tras el prefijo 'T-' y antes del '.pdf'
            const match = archivo.nombre.match(/T-([\d\s]+)\.pdf$/i);

            if (match) {
                const cedulaExtraida = match[1].trim();

                if (empleadosMap.has(cedulaExtraida)) {
                    const datos = empleadosMap.get(cedulaExtraida);
                    const rawPrefix = txtPrefix ? txtPrefix.value.trim() : '';
                    const cleanPrefix = sanitizeFileName(rawPrefix);

                    const nuevoNombre = cleanPrefix
                        ? `${cleanPrefix} ${cedulaExtraida} ${datos.nombre}.pdf`
                        : `${cedulaExtraida} ${datos.nombre}.pdf`;

                    const rutaDestino = `${datos.proceso}/${nuevoNombre}`;
                    
                    nuevoZip.file(rutaDestino, archivo.blob);
                    procesadosOk++;
                } else {
                    // Control de anomalías: el PDF cumple la nomenclatura pero la cédula no figura en la BD
                    nuevoZip.file(`NO_ENCONTRADOS/${archivo.nombre}`, archivo.blob);
                    log(`⚠️ Cédula '${cedulaExtraida}' no encontrada en la base de datos. Movido a 'NO_ENCONTRADOS'.`);
                    procesadosOk++;
                }
            } else {
                log(`❌ Patrón de nombre omitido (Falta nomenclatura T-...pdf): ${archivo.nombre}`);
            }
        });

        if (procesadosOk === 0) {
            log("❌ Proceso cancelado: Ningún archivo cumple con los requisitos del nombre.");
            processBtn.disabled = false;
            return;
        }

        // Empaquetar y disparar la descarga automatizada
        log("📦 Compilando la nueva estructura de carpetas organizadas...");
        const blobFinal = await nuevoZip.generateAsync({ type: "blob" });
        
        const link = document.createElement("a");
        link.href = URL.createObjectURL(blobFinal);
        link.download = "Personal_Organizado_Por_Proceso.zip";
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);

        log("✔️ ¡Ficheros renombrados y organizados descargados con éxito!");

    } catch (error) {
        log(`❌ Error de procesamiento: ${error.message}`);
        console.error(error);
    } finally {
        processBtn.disabled = false;
    }
});
